export function label(key: LabelKey): string {
    let lang = 'en';
    try {
        lang = Settings.getSetting('translation.language')?.observableValue?.() ?? 'en';
    } catch {
        lang = 'en';
    }
    return lang === 'fr' ? fr[key] : en[key];
}


